// Regenerate the illustrative video and audio examples with:
// node qdrant-landing/content/documentation/headless/chunking/render-media-examples.mjs
// These are editable schematics, not recorded media or measured model output.
// No dependencies or network requests are needed.
import { readFile, writeFile } from 'node:fs/promises';

const destination = new URL('../../../../static/guides_data/chunking/', import.meta.url);
const fontSource = await readFile(new URL('complete-task.svg', destination), 'utf8');
const fontFace = fontSource.match(/@font-face\{[^}]+\}/)?.[0];
if (!fontFace?.includes('data:font/woff;base64,')) {
  throw new Error('The chunking reference must contain its embedded Geist Mono font.');
}

const color = {
  surface: '#f0f3fa', border: '#d3d9eb', fg: '#303547', muted: '#656b7f',
  violet: '#6047ff', teal: '#00838f',
};
const escape = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;',
})[character]);
const text = (x, y, label, { size = 26, fill = color.fg, weight = 400 } = {}) =>
  `<text x="${x}" y="${y}" font-size="${size}" font-weight="${weight}" fill="${fill}">${escape(label)}</text>`;
const panel = (x, y, width, height, stroke) =>
  `<rect x="${x}" y="${y}" width="${width}" height="${height}" rx="4" fill="${stroke}" fill-opacity="0.08" stroke="${stroke}" stroke-width="2"/>`;
const line = (x1, y1, x2, y2, { arrow = false, stroke = color.muted } = {}) =>
  `<line x1="${x1}" y1="${y1}" x2="${x2}" y2="${y2}" stroke="${stroke}" stroke-width="2"${arrow ? ' marker-end="url(#arrow)"' : ''}/>`;

function document(title, description, height, drawing) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="${height}" viewBox="0 0 640 ${height}" role="img" aria-labelledby="title desc">
<title id="title">${escape(title)}</title>
<desc id="desc">${escape(description)}</desc>
<!-- Generated by content/documentation/headless/chunking/render-media-examples.mjs.
     Illustrative timeline, not an actual recording or model output.
     Theme-neutral light export; SVG owns the only enclosing frame. -->
<defs>
  <style>${fontFace}text{font-family:'Geist Mono',ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}</style>
  <marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 Z" fill="${color.muted}"/></marker>
</defs>
<rect x="0.5" y="0.5" width="639" height="${height - 1}" rx="6" fill="${color.surface}" stroke="${color.border}" stroke-width="1"/>
${drawing.join('\n')}
</svg>
`;
}

function video() {
  return document(
    'Video chunking: retain the visual event and its transcript',
    'Illustrative export walkthrough, not an actual recording. The full clip spans 00:00–00:08. At 00:00 the export menu opens with PDF, DOCX, and TXT options. At 00:03 PDF is selected. At 00:06 the download is ready as report.pdf. The transcript at 00:02–00:04 says, “Choose this format.” The spoken words alone do not identify PDF; the visual event supplies that evidence.',
    570,
    [
      text(24, 40, 'Export walkthrough', { size: 28, weight: 600 }),
      text(24, 78, 'Illustrative timeline', { fill: color.muted }),
      text(24, 118, 'Clip: 00:00–00:08'),
      text(24, 180, '00:00', { fill: color.muted }),
      panel(146, 146, 470, 88, color.muted),
      text(166, 180, 'Open export menu'),
      text(166, 218, 'PDF · DOCX · TXT'),
      line(381, 238, 381, 252, { arrow: true }),
      text(24, 291, '00:03', { fill: color.muted }),
      panel(146, 258, 470, 70, color.violet),
      text(166, 302, 'PDF selected', { weight: 600, fill: color.violet }),
      line(381, 332, 381, 348, { arrow: true }),
      text(24, 389, '00:06', { fill: color.muted }),
      panel(146, 354, 470, 88, color.teal),
      text(166, 389, 'Download ready'),
      text(166, 426, 'report.pdf', { fill: color.teal, weight: 600 }),
      text(24, 480, 'Transcript · 00:02–00:04', { fill: color.muted }),
      text(24, 516, '“Choose this format.”'),
      text(24, 550, 'No file format is named.', { fill: color.muted }),
    ],
  );
}

function audio() {
  return document(
    'Audio chunking: keep the question with its conditional answer',
    'Illustrative release-planning call, not an actual recording or measured waveform. Speaker A asks “When do we ship the update?” at 00:00–00:03. Speaker B answers “Friday, if the load test passes.” at 00:03–00:07. One transcript chunk retains the full 00:00–00:07 exchange so the condition stays attached to the answer. A separate alarm tone occurs at 00:08–00:10 and has no transcript words; answering questions about this event requires audio evidence.',
    590,
    [
      text(24, 40, 'Release-planning call', { size: 28, weight: 600 }),
      text(24, 78, 'Illustrative timeline', { fill: color.muted }),
      text(24, 120, 'Text chunk: 00:00–00:07', { fill: color.violet }),
      panel(24, 140, 592, 222, color.violet),
      text(40, 176, '00:00–00:03 · Speaker A'),
      text(40, 214, 'When do we ship the update?'),
      line(40, 246, 600, 246, { stroke: color.border }),
      text(40, 286, '00:03–00:07 · Speaker B'),
      text(40, 324, 'Friday, if the load test passes.'),
      text(24, 404, 'Separate sound event', { fill: color.teal }),
      panel(24, 422, 592, 108, color.teal),
      text(40, 460, '00:08–00:10 · Alarm tone'),
      text(40, 500, 'No transcript words'),
      text(24, 570, 'Retain audio for sound questions.', { fill: color.muted }),
    ],
  );
}

for (const [name, svg] of [['video-example.svg', video()], ['audio-example.svg', audio()]]) {
  await writeFile(new URL(name, destination), svg);
  console.log(`Wrote ${name}`);
}
