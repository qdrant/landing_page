#!/usr/bin/env bash
#
# Append a Link header to public/_headers for every page that has an index.md,
# pointing agents at the Markdown version before they parse the HTML.
#
# Generated rather than a /* rule in netlify.toml because a relative
# <index.md> on every URL also fired on the homepage, llms.txt, and assets,
# where it resolved to a 404.
set -euo pipefail

PUBLIC="${1:-public}"
[ -d "$PUBLIC" ] || { echo "md-link-headers: no such directory: $PUBLIC" >&2; exit 1; }

written=0
{
  printf '\n# Generated by scripts/emit-md-link-headers.sh\n'
  while IFS= read -r -d '' src; do
    path="${src#"$PUBLIC"}"
    printf '%s\n  Link: <%s>; rel="alternate"; type="text/markdown"\n' "${path%index.md}" "$path"
    written=$((written + 1))
  done < <(find "$PUBLIC" -type f -name index.md -print0 | sort -z)
} >> "$PUBLIC/_headers"

echo "md-link-headers: wrote ${written}" >&2
