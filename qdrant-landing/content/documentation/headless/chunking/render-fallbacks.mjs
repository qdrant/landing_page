// Regenerate the theme-neutral SVG fallbacks with:
// node qdrant-landing/content/documentation/headless/chunking/render-fallbacks.mjs
// No dependencies or network requests are needed. The existing chunking figure
// supplies the same embedded Geist Mono font used by these standalone exports.
import { readFile, writeFile } from 'node:fs/promises';

const destination = new URL('../../../../static/guides_data/chunking/', import.meta.url);
const fontSource = await readFile(new URL('complete-task.svg', destination), 'utf8');
const fontFace = fontSource.match(/@font-face\{[^}]+\}/)?.[0];
if (!fontFace?.includes('data:font/woff;base64,')) {
  throw new Error('The chunking reference must contain its embedded Geist Mono font.');
}

const color = {
  surface: '#f0f3fa', border: '#d3d9eb', fg: '#303547', muted: '#656b7f',
  violet: '#6047ff', purple: '#9c27b0', teal: '#00838f', red: '#dc244c',
};
const escape = value => String(value).replace(/[&<>"']/g, character => ({
  '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&apos;',
})[character]);
const number = value => Number(value.toFixed(2));
const text = (x, y, label, { size = 26, fill = color.fg, anchor = 'start', weight = 400 } = {}) =>
  `<text x="${number(x)}" y="${number(y)}" font-size="${size}" font-weight="${weight}" fill="${fill}" text-anchor="${anchor}">${escape(label)}</text>`;
const rect = (x, y, width, height, stroke, { opacity = 0.08, radius = 4 } = {}) =>
  `<rect x="${number(x)}" y="${number(y)}" width="${number(width)}" height="${number(height)}" rx="${radius}" fill="${stroke}" fill-opacity="${opacity}" stroke="${stroke}" stroke-width="2"/>`;
const line = (x1, y1, x2, y2, { arrow = false, stroke = color.muted, dash } = {}) =>
  `<line x1="${number(x1)}" y1="${number(y1)}" x2="${number(x2)}" y2="${number(y2)}" stroke="${stroke}" stroke-width="2"${arrow ? ' marker-end="url(#arrow)"' : ''}${dash ? ` stroke-dasharray="${dash}"` : ''}/>`;

function document(title, description, height, drawing) {
  return `<svg xmlns="http://www.w3.org/2000/svg" width="640" height="${height}" viewBox="0 0 640 ${height}" role="img" aria-labelledby="title desc">
<title id="title">${escape(title)}</title>
<desc id="desc">${escape(description)}</desc>
<!-- Generated by content/documentation/headless/chunking/render-fallbacks.mjs.
     Theme-neutral light export; SVG owns the only enclosing frame.
     Colors and font follow the filterable-HNSW and chunking references. -->
<defs>
  <style>${fontFace}text{font-family:'Geist Mono',ui-monospace,SFMono-Regular,Menlo,Consolas,monospace}</style>
  <marker id="arrow" viewBox="0 0 10 10" refX="9" refY="5" markerWidth="6" markerHeight="6" orient="auto-start-reverse"><path d="M0 0 L10 5 L0 10 Z" fill="${color.muted}"/></marker>
</defs>
<rect x="0.5" y="0.5" width="639" height="${height - 1}" rx="6" fill="${color.surface}" stroke="${color.border}" stroke-width="1"/>
${drawing.join('\n')}
</svg>
`;
}

function decisionFlow() {
  const drawing = [text(24, 40, 'Five Decisions for Chunking', { weight: 600 })];
  const steps = [
    ['Inspect Sources', 'Is the source evidence intact?'],
    ['Choose Boundaries', 'Do needed facts stay together?'],
    ['Set Size and Overlap', 'Do both input budgets fit?'],
    ['Add Missing Context', 'Does each chunk make sense alone?'],
    ['Test Final Evidence', 'Where does evidence disappear?'],
  ];
  steps.forEach(([label, question], index) => {
    const y = 74 + index * 104;
    drawing.push(rect(24, y, 592, 80, index === 0 ? color.violet : color.muted, { opacity: index === 0 ? 0.08 : 0.03 }));
    drawing.push(text(40, y + 31, `${index + 1}. ${label}`, { weight: 600 }));
    drawing.push(text(40, y + 62, question));
    if (index < steps.length - 1) drawing.push(line(320, y + 84, 320, y + 100, { arrow: true }));
  });
  drawing.push(text(24, 614, 'Trace failures to the relevant step.'));
  return document('Five decisions for setting up chunking',
    'Follow five connected decisions. First, inspect whether extracted source evidence is intact. Second, choose boundaries that keep the facts needed for a question together. Third, fit complete embedding inputs and the assembled answer context within their separate model budgets, adding overlap only where it helps. Fourth, add source identity or missing source context at the appropriate stage. Fifth, test final evidence coverage and answer correctness separately. Missing source evidence leads back to inspection; a retrieval miss calls for inspecting the query, filters, and representation; dropped context calls for inspecting assembly, expansion, duplicates, and budgets. If evidence is present but the answer is wrong, inspect the answering stage. This diagram illustrates decisions and does not run or validate a pipeline.',
    640, drawing);
}

function fixed() {
  const wordCount = 31;
  const x = index => 36 + (index - 1) * 568 / wordCount;
  const wordWidth = 568 / wordCount;
  const drawing = [
    text(24, 40, '31 words → 12-word windows', { size: 26, weight: 600 }),
    text(24, 78, 'Dashed band = repeated words', { fill: color.muted }),
    text(24, 120, 'Overlap 0 · stride 12 words'),
  ];
  const window = (first, last, y, overlap = 0) => {
    const start = x(first) + 1;
    const width = (last - first + 1) * wordWidth - 2;
    drawing.push(rect(start, y, width, 36, color.violet));
    // A short final window cannot fit a 26px range label. Its open row leaves
    // room for an adjacent label without shrinking mobile text.
    drawing.push(text(width < 100 ? start - 12 : start + width / 2, y + 26, `${first}–${last}`, {
      anchor: width < 100 ? 'end' : 'middle',
    }));
    if (overlap) {
      drawing.push(`<rect x="${number(start)}" y="${y + 31}" width="${number(overlap * wordWidth - 2)}" height="5" fill="${color.teal}" fill-opacity="0.15" stroke="${color.teal}" stroke-width="2" stroke-dasharray="4 3"/>`);
    }
  };
  [[1, 12], [13, 24], [25, 31]].forEach(([first, last]) => window(first, last, 138));
  drawing.push(text(24, 222, 'Overlap 3 · stride 9 words'));
  [[1, 12], [10, 21], [19, 30], [28, 31]].forEach(([first, last], index) =>
    window(first, last, 238 + index * 40, index ? 3 : 0));
  drawing.push(line(36, 406, 604, 406));
  [[1, 'start'], [10, 'middle'], [19, 'middle'], [31, 'end']].forEach(([index, anchor]) => {
    const at = index === 31 ? 604 : x(index);
    drawing.push(line(at, 403, at, 410));
    drawing.push(text(at, 432, index, { fill: color.muted, anchor }));
  });
  return document('Fixed chunking: 12-word windows over 31 source words',
    'Both examples use the same 31-word source and a 12-word window. Without overlap, the chunks cover words 1–12, 13–24, and 25–31, advancing 12 words at a time. With 3 words of overlap, they cover 1–12, 10–21, 19–30, and 28–31, advancing 9 words at a time. Dashed teal bands mark the 3 repeated source positions at the beginning of each later chunk. Bars use the same source-word position scale; final chunks can be shorter. These are word counts, not model-token counts.',
    440, drawing);
}

