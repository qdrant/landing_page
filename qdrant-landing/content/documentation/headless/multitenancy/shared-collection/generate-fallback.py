"""Run `uv run <path-to-this-file>` to regenerate the light, static fallback."""

from base64 import b64encode
from html import escape
from io import BytesIO
from pathlib import Path
import re
import subprocess
import xml.etree.ElementTree as ET

from fontTools import subset

diagram = Path(__file__).resolve().parent
root = diagram.parents[4]
module = diagram / "index.js"
source = """
import { readFile } from 'node:fs/promises';
const code = await readFile(process.argv[1], 'utf8');
const { renderSvg } = await import('data:text/javascript;base64,' + Buffer.from(code).toString('base64'));
process.stdout.write(renderSvg(false, 'shared-collection-fallback'));
"""
svg = subprocess.check_output(
    ["node", "--input-type=module", "-e", source, str(module)], text=True
)
# Standalone images use literal light colors; inline SVG uses the page tokens.
svg = re.sub(r"var\(--qi-[\w-]+, ([^)]+)\)", r"\1", svg)
document = ET.fromstring(svg)
characters = "".join(
    element.text or ""
    for element in document.iter("{http://www.w3.org/2000/svg}text")
)
font_dir = root / "themes/qdrant-2024/static/fonts/Geist_Mono"
options = subset.Options()
font = subset.load_font(str(font_dir / "GeistMono-VariableFont_wght.ttf"), options)
font.recalcTimestamp = False
subsetter = subset.Subsetter(options=options)
subsetter.populate(text=characters)
subsetter.subset(font)
font.flavor = "woff2"
output = BytesIO()
font.save(output)
font_data = b64encode(output.getvalue()).decode()
license_text = escape("\n".join(line.rstrip() for line in (font_dir / "OFL.txt").read_text().splitlines()))
style = (
    "<style>@font-face {font-family:'Geist Mono';font-style:normal;"
    "font-weight:100 900;src:url(data:font/woff2;base64,"
    + font_data
    + ") format('woff2')}</style>"
)
svg = svg.replace(
    "<defs>", f"<metadata>{license_text}</metadata><defs>{style}", 1
)
target = root / "static/articles_data/multitenancy/multitenancy-single.svg"
target.write_text("<!-- Generated by shared-collection/generate-fallback.py. -->\n" + svg + "\n")
print(f"Generated {target.name}: {target.stat().st_size} bytes")
