function slidingWindow() {
  const drawing = [
    text(24, 40, 'Slide a three-sentence window', { weight: 600 }),
    text(24, 78, 'S3: linked files · S4: download', { fill: color.muted }),
    text(24, 116, 'Stride 3 → no overlap'),
  ];
  const window = (first, last, y, stroke, repeated = false) => {
    const start = 24 + (first - 1) * 98;
    drawing.push(rect(start, y, (last - first + 1) * 98 - 8, 40, stroke));
    for (let i = first; i <= last; i += 1) {
      drawing.push(text(24 + (i - 1) * 98 + 45, y + 29, `S${i}`, { anchor: 'middle' }));
    }
    if (repeated) {
      drawing.push(`<rect x="${start}" y="${y}" width="90" height="40" rx="4" fill="none" stroke="${color.fg}" stroke-width="2" stroke-dasharray="5 4"/>`);
    }
  };
  window(1, 3, 134, color.violet);
  window(4, 6, 134, color.purple);
  drawing.push(text(24, 222, 'Stride 2 → overlap 1 sentence'));
  window(1, 3, 240, color.violet);
  window(3, 5, 290, color.purple, true);
  window(5, 6, 340, color.teal, true);
  drawing.push(text(24, 420, 'Dashed: S3 and S5 repeat.'));
  return document('Sliding-window chunking: changing stride while holding window size fixed',
    'The source has six sentences. S3 describes linked-file references and S4 gives the separate-download instruction. Three-sentence windows at stride 3 cover S1–S3 and S4–S6, so S3 and S4 are separated. At stride 2, the windows cover S1–S3, S3–S5, and S5–S6. The middle window keeps S3 and S4 together. Dashed outlines mark S3 and S5 repeated from the preceding windows, for two repeated sentence appearances. The final window is shorter. These are sentence counts, not token counts.',
    440, drawing);
}

function semantic() {
  const centers = [80, 200, 320, 440, 560];
  const scores = [0.78, 0.56, 0.84, 0.18];
  const drawing = [text(24, 40, 'Semantic: compare sentence vectors', { size: 26, weight: 600 })];
  centers.forEach((center, index) => drawing.push(text(center, 86, `S${index + 1}`, { size: 26, anchor: 'middle' })));
  scores.forEach((score, index) => {
    drawing.push(line(centers[index] + 23, 80, centers[index + 1] - 23, 80));
    drawing.push(text((centers[index] + centers[index + 1]) / 2, 120, score.toFixed(2), {
      anchor: 'middle', fill: index === 1 ? color.violet : index === 3 ? color.red : color.muted,
    }));
  });
  drawing.push(text(320, 153, 'Illustrative adjacent scores', { anchor: 'middle', fill: color.muted }));
  const groups = (y, ranges, palette) => {
    ranges.forEach(([first, last], index) => {
      const start = centers[first - 1] - 56;
      const end = centers[last - 1] + 56;
      drawing.push(rect(start, y, end - start, 52, palette[index]));
      for (let sentence = first; sentence <= last; sentence += 1) {
        drawing.push(text(centers[sentence - 1], y + 35, `S${sentence}`, { size: 26, anchor: 'middle' }));
      }
    });
  };
  drawing.push(text(24, 195, 'Threshold 0.35 → 2 chunks'));
  groups(211, [[1, 4], [5, 5]], [color.violet, color.purple]);
  drawing.push(text(24, 303, 'Threshold 0.65 → 3 chunks'));
  groups(319, [[1, 2], [3, 4], [5, 5]], [color.violet, color.purple, color.teal]);
  drawing.push(text(24, 418, '0.56 < 0.65: add a boundary'));
  return document('Semantic chunking: changing an illustrative similarity threshold',
    'The source has five sentences: S1 defines an export, S2 gives the steps, S3 describes file references, S4 gives the separate-download exception, and S5 covers billing. Illustrative similarities between adjacent sentences are 0.78, 0.56, 0.84, and 0.18. Split when similarity is strictly less than the threshold. At 0.35, the groups are S1–S4 and S5. At 0.65, the 0.56 similarity introduces another boundary, giving S1–S2, S3–S4, and S5. The scores are supplied examples, not measured embedding results.',
    440, drawing);
}

